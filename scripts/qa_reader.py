from pathlib import Path
from playwright.sync_api import sync_playwright
from datetime import datetime, timezone
import json, os, shutil
ROOT=Path(__file__).resolve().parents[1]
html_text=(ROOT/'DEVELOPMENT_PLAN.html').read_text()
checks=[];errors=[];requests=[]
def check(name,ok,detail=''):
    checks.append({'check':name,'pass':bool(ok),'detail':detail})
    if not ok:raise AssertionError(name+': '+detail)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('BROWSER_PATH') or shutil.which('chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url))
    page.set_content(html_text,wait_until='load')
    check('All planned PR cards present',page.locator('.pr-card').count()==210)
    check('Correct document title','Development Plan' in page.title())
    check('No desktop document horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
    page.screenshot(path=str(ROOT/'validation/reader-desktop.png'),full_page=False)
    page.locator('#pr-query').fill('GDN-069')
    check('PR identifier filtering',page.locator('.pr-card:not([hidden])').count()==1)
    page.locator('#expand-prs').click()
    check('Expand visible PR',page.locator('#gdn-069').get_attribute('open') is not None)
    page.locator('#gdn-069').scroll_into_view_if_needed()
    page.screenshot(path=str(ROOT/'validation/reader-pr-example.png'),full_page=False)
    page.locator('#clear-filters').click()
    check('Clear restores all PRs',page.locator('.pr-card:not([hidden])').count()==210)
    page.locator('#status-filter').select_option('conditional')
    check('Conditional filter returns exactly 14',page.locator('.pr-card:not([hidden])').count()==14)
    page.locator('#clear-filters').click()
    page.locator('#feature-filter').select_option('F08')
    visible=page.locator('.pr-card:not([hidden])').count()
    check('Funding feature filter has results',visible>0)
    check('Feature filter exact membership',page.locator('.pr-card:not([hidden])').evaluate_all("els=>els.every(e=>e.dataset.features.split(' ').includes('F08'))"))
    page.locator('#clear-filters').click()
    page.locator('#phase-filter').select_option('P08')
    check('Research workstream has 18 PRs',page.locator('.pr-card:not([hidden])').count()==18)
    # Hash navigation unhides a filtered-out card and opens it.
    page.evaluate("location.hash='gdn-051'")
    page.wait_for_timeout(150)
    check('Deep link opens and reveals PR',page.locator('#gdn-051').get_attribute('open') is not None and page.locator('#gdn-051').is_visible())
    page.locator('#global-query').fill('GDN-126')
    page.wait_for_timeout(200)
    check('Global search reveals results',page.locator('#search-results').is_visible() and page.locator('#result-list li').count()>0)
    check('Global results include target PR',page.locator('#result-list a[href="#gdn-126"]').count()==1)
    page.locator('#global-query').fill('zzzznotpresent12345');page.wait_for_timeout(200)
    check('No-result explanation','No match' in page.locator('#result-list').inner_text())
    page.locator('#clear-global').click()
    check('Search clearing hides results',not page.locator('#search-results').is_visible())
    page.keyboard.press('Control+k')
    check('Keyboard search shortcut',page.locator('#global-query').evaluate('e=>e===document.activeElement'))
    # Check all fragment targets without leaving the page.
    bad=page.locator('a[href^="#"]').evaluate_all("els=>els.map(e=>e.getAttribute('href').slice(1)).filter(id=>id&&!document.getElementById(id))")
    check('No broken internal fragment links',not bad,str(bad[:5]))
    check('No external automatic network requests',not [r for r in requests if r.startswith(('http://','https://'))])
    check('No JavaScript errors',not errors,str(errors))
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
    mobile.set_content(html_text,wait_until='load')
    check('Mobile no horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
    check('Mobile contents initially collapsed',mobile.locator('#contents').get_attribute('open') is None)
    mobile.screenshot(path=str(ROOT/'validation/reader-mobile.png'),full_page=False)
    mobile.locator('#pr-query').fill('GDN-206');mobile.locator('#expand-prs').click()
    check('Mobile filter and expand work',mobile.locator('.pr-card:not([hidden])').count()==1 and mobile.locator('#gdn-206').get_attribute('open') is not None)
    nojs=browser.new_page(java_script_enabled=False,viewport={'width':1280,'height':900})
    nojs.set_content(html_text,wait_until='load')
    check('No-JS content remains available',nojs.locator('.pr-card').count()==210 and 'The Garden' in nojs.locator('h1').inner_text())
    nojs.locator('#gdn-001 summary').click()
    check('Native details work without JS',nojs.locator('#gdn-001').get_attribute('open') is not None)
    browser.close()
report={'artifact':'portable plan reader, not Garden application','recorded_at':datetime.now(timezone.utc).isoformat(),'browser':'Playwright system Chromium, supplied local HTML (file URL navigation unavailable)' ,'checks':checks,'passed':sum(x['pass'] for x in checks),'failed':sum(not x['pass'] for x in checks),'javascript_errors':errors,'external_network_requests':[r for r in requests if r.startswith(('http://','https://'))],'limits':['Not a WCAG certification or full assistive-technology audit.','No website deployment or production functionality tested.','Screenshots inspected separately.']}
(ROOT/'validation/reader-qa.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({'passed':report['passed'],'failed':report['failed'],'errors':errors},indent=2))
